DROP SCHEMA IF EXISTS manit_hostel_management CASCADE;
CREATE SCHEMA manit_hostel_management;

CREATE TABLE manit_hostel_management.hostel_master (       -- ASSUMED table
    hostel_id   integer PRIMARY KEY,
    hostel_name varchar(100) NOT NULL,
    hostel_type varchar(5)   NOT NULL CHECK (hostel_type IN ('BOYS','GIRLS'))
);
CREATE TABLE manit_hostel_management.hostel_allot (
    allot_id           bigserial PRIMARY KEY,
    allot_student_id   varchar(20) NOT NULL,   -- ASSUMED to hold studentuid (as text; the snippet quotes it)
    hostel_id          integer     REFERENCES manit_hostel_management.hostel_master,   -- ASSUMED (snippet reads only room no.)
    allot_room_no      varchar(10),            -- known
    allot_status       char(1) NOT NULL,       -- known: '1' = allotted, '0' = vacated
    allot_final_status char(1) NOT NULL,       -- known: '1' = final, '0' = only requested/pending
    delete_status      char(1) NOT NULL,       -- known: '1' = deleted record
    allot_date         date
);
CREATE INDEX hostel_allot_student_idx ON manit_hostel_management.hostel_allot (allot_student_id);
-- The CURRENT allotment of a student is the row with allot_status='1' AND allot_final_status='1' AND delete_status='0'.

