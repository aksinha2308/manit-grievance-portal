    public function __construct()
    {
        parent::__construct();

        // The portal stores every time in UTC and reads timestamps back in ISO format. Make the PostgreSQL session
        // use exactly that, whatever the server's own defaults are (a Windows install may use the local time zone
        // and a day-month-year date style) and even if the .env line for it is missing.
        if (($this->default['DBDriver'] ?? '') === 'Postgre') {
            $opts = trim((string) ($this->default['options'] ?? ''));
            if (! str_contains($opts, 'timezone=')) {
                $opts .= ' -c timezone=UTC';
            }
            if (! str_contains($opts, 'datestyle=')) {
                $opts .= ' -c datestyle=ISO,YMD';
            }
            $this->default['options'] = trim($opts);
        }

        // Ensure that we always set the database group to 'tests' if
        // we are currently running an automated test suite, so that
        // we don't overwrite live data on accident.
        if (ENVIRONMENT === 'testing') {
            $this->defaultGroup = 'tests';
        }
    }
